// Thumbnails for the presets window: every gallery preset photographed on the
// real Desmos pages, 2D and 3D, through the built extension, shrunk to a small
// WebP each. Run after `npm run build`, and again whenever a preset's look
// changes:
//
//   node docs/mockups/vector-3d-arrows/preset-thumbnails.cjs
//
// Writes src/plugins/vector-tools/components/presetThumbnails.ts.
const puppeteer = require("puppeteer");
const { writeFileSync } = require("node:fs");
const { join } = require("node:path");

const root = join(__dirname, "..", "..", "..");
// Twice the size the window shows them at, for high-density screens.
const WIDTH = 92;
const HEIGHT = 68;

async function shoot(page, product) {
  await page.goto(`https://www.desmos.com/${product}`);
  await page.waitForSelector(".dsm-pillbox-and-popover", { timeout: 60000 });
  await page.evaluate(() => DSM.enablePlugin("vector-tools"));
  await page.waitForFunction(
    () => DSM.enabledPlugins["vector-tools"] !== undefined
  );
  const ids = await page.evaluate(() =>
    DSM.enabledPlugins["vector-tools"].gallery.map((p) => p.id)
  );
  const out = {};
  for (const id of ids) {
    await page.evaluate((id) => {
      const vt = DSM.enabledPlugins["vector-tools"];
      if (vt.isFlowRunning) vt.toggleFlow();
      vt.applyGalleryPreset(id, true);
      if (!vt.isFlowRunning) vt.toggleFlow();
    }, id);
    await new Promise((r) => setTimeout(r, 4000));
    const rect = await page.evaluate((product) => {
      const r = (
        product === "3d"
          ? Calc.controller.grapher3d.webglCanvas
          : document.querySelector(".dcg-grapher")
      ).getBoundingClientRect();
      // The middle of the picture, in the window's 4:3, leaving out the
      // graph's own buttons at the edges.
      const w = Math.min(r.width, r.height) * (product === "3d" ? 0.78 : 0.9);
      const h = w * 0.74;
      return {
        x: r.x + (r.width - w) / 2,
        y: r.y + (r.height - h) / 2,
        width: w,
        height: h,
      };
    }, product);
    const png = await page.screenshot({ encoding: "base64", clip: rect });
    out[id] = await page.evaluate(
      async (png, w, h) => {
        // In the page being photographed: a background tab may never get
        // round to decoding an image.
        const blob = await (await fetch(`data:image/png;base64,${png}`)).blob();
        const image = await createImageBitmap(blob);
        const canvas = document.createElement("canvas");
        canvas.width = w;
        canvas.height = h;
        const g = canvas.getContext("2d");
        g.imageSmoothingQuality = "high";
        g.drawImage(image, 0, 0, w, h);
        return canvas.toDataURL("image/webp", 0.82);
      },
      png,
      WIDTH,
      HEIGHT
    );
  }
  return out;
}

(async () => {
  const extension = join(root, "dist");
  const browser = await puppeteer.launch({
    headless: "new",
    args: [
      `--disable-extensions-except=${extension}`,
      `--load-extension=${extension}`,
    ],
  });
  const page = await browser.newPage();
  await page.setViewport({ width: 1100, height: 760 });
  const plane = await shoot(page, "calculator");
  await page.close();
  // A fresh tab for Desmos 3D: navigating the calculator's tab there leaves
  // its 3D grapher without a canvas.
  const page3d = await browser.newPage();
  await page3d.setViewport({ width: 1100, height: 760 });
  const space = await shoot(page3d, "3d");
  await browser.close();
  const entries = Object.keys(plane)
    .map(
      (id) =>
        `  ${JSON.stringify(id)}: {\n    plane:\n      ${JSON.stringify(plane[id])},\n    space:\n      ${JSON.stringify(space[id])},\n  },`
    )
    .join("\n");
  const ts = `/**
 * Each preset's thumbnail for the presets window, as the flow draws it on the
 * real Desmos pages: \`plane\` on the calculator, \`space\` on Desmos 3D.
 *
 * Generated by docs/mockups/vector-3d-arrows/preset-thumbnails.cjs — run it
 * again after changing how a preset looks. ${WIDTH}×${HEIGHT} WebP, twice the
 * size shown, so they stay sharp on high-density screens.
 */
export const PRESET_THUMBNAILS: Readonly<
  Record<string, { plane: string; space: string }>
> = {
${entries}
};
`;
  const path = join(
    root,
    "src",
    "plugins",
    "vector-tools",
    "components",
    "presetThumbnails.ts"
  );
  writeFileSync(path, ts);
  console.log("ok", Math.round(ts.length / 1024), "KB");
})();
